#!/usr/bin/env python3
"""
boardgen — turn an OSOlogic MCU board profile (board.yaml) into board_map.c/.h.

The generated map binds osodb tags to physical pins/peripherals and wires the
hard-real-time control loops, calling only hal.h. Port to any MCU/SoC by writing a
board.yaml and running this — the control core never changes.

  boardgen.py boards/rp2040_demo.board.yaml -o generated/

No third-party deps: a tiny parser reads the constrained YAML this format uses
(top-level scalars, one nested map `federation:`, and `io:`/`control:` lists of
inline `{ ... }` maps). Have the LLM emit the board.yaml from a datasheet if you like.

(C) 2026 Roig Borrell S.L. and Ibercomp S.L. — AGPL-3.0-or-later
"""
import sys, os, re


def _val(s):
    s = s.strip()
    if s.lower() in ("true", "false"):
        return s.lower() == "true"
    try:
        return int(s)
    except ValueError:
        pass
    try:
        return float(s)
    except ValueError:
        pass
    return s.strip().strip('"').strip("'")


def _inline_map(s):
    s = s.strip()
    if s.startswith("{"):
        s = s[1:-1]
    out = {}
    for part in s.split(","):
        if ":" in part:
            k, v = part.split(":", 1)
            out[k.strip()] = _val(v)
    return out


def parse(path):
    prof = {"io": [], "control": [], "federation": {}}
    section = None
    for raw in open(path):
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        if line.startswith((" ", "\t", "-")):
            item = line.strip()
            if item.startswith("- "):
                prof[section].append(_inline_map(item[2:]))
            elif section == "federation" and ":" in item:
                k, v = item.split(":", 1)
                prof["federation"][k.strip()] = _val(v)
            continue
        # top-level "key: value" or "key:"
        key, _, rest = line.partition(":")
        key = key.strip()
        rest = rest.strip()
        if key in ("io", "control", "federation"):
            section = key
        else:
            prof[key] = _val(rest)
            section = None
    return prof


def cident(tag):
    return "idx_" + re.sub(r"[^A-Za-z0-9]", "_", tag)


def gen(prof):
    io = prof["io"]
    ctrl = prof["control"]
    board = prof.get("board", "board")

    # every tag that needs defining: io tags + control sp tags not already an io tag
    io_tags = {e["tag"] for e in io}
    sp_tags = [c["sp"] for c in ctrl if c.get("sp") and c["sp"] not in io_tags]

    H = []
    H.append('#ifndef BOARD_MAP_H')
    H.append('#define BOARD_MAP_H')
    H.append('#include "osodb_embedded.h"')
    H.append('/* GENERATED by boardgen from %s.board.yaml — do not edit by hand. */' % board)
    H.append('extern const char *BOARD_NAME;')
    H.append('void board_io_define(osodb_t *db);')
    H.append('void board_io_init(void);')
    H.append('void board_io_read_inputs(osodb_t *db, uint32_t now_ms);')
    H.append('void board_io_write_outputs(osodb_t *db);')
    H.append('void board_control_step(osodb_t *db, double dt, uint32_t now_ms);')
    H.append('#endif')

    C = []
    C.append('/* GENERATED by boardgen from %s.board.yaml — do not edit by hand. */' % board)
    C.append('#include "board_map.h"')
    C.append('#include "hal.h"')
    C.append('#include "pid.h"')
    C.append('')
    C.append('const char *BOARD_NAME = "%s";' % board)
    C.append('')
    # cached indices
    for t in list(io_tags) + sp_tags:
        C.append('static int %s;' % cident(t))
    C.append('')
    # define
    C.append('void board_io_define(osodb_t *db) {')
    for e in io:
        typ = "OSODB_BOOL" if e.get("type") == "bool" else "OSODB_REAL"
        acc = "OSODB_RW" if e.get("dir") == "out" else "OSODB_RO"
        C.append('    %s = osodb_define(db, "%s", %s, %s, 0);' % (cident(e["tag"]), e["tag"], typ, acc))
    for sp in sp_tags:
        C.append('    %s = osodb_define(db, "%s", OSODB_REAL, OSODB_RW, 0);' % (cident(sp), sp))
    C.append('}')
    C.append('')
    # init
    C.append('void board_io_init(void) {')
    for e in io:
        if e["kind"] == "gpio":
            C.append('    hal_gpio_config(%d, %s, %s);' % (
                e["pin"], "true" if e["dir"] == "out" else "false",
                "true" if e.get("active_low") else "false"))
        elif e["kind"] == "pwm":
            C.append('    hal_pwm_config(%d);' % e["pin"])
        elif e["kind"] == "adc":
            C.append('    hal_adc_config(%d);' % e["channel"])
    C.append('}')
    C.append('')
    # read inputs
    C.append('void board_io_read_inputs(osodb_t *db, uint32_t now_ms) {')
    for e in io:
        if e["dir"] != "in":
            continue
        if e["kind"] == "gpio":
            inv = " ? 0 : 1" if e.get("active_low") else " ? 1 : 0"
            C.append('    osodb_set_value(db, %s, hal_gpio_read(%d)%s, now_ms);' % (cident(e["tag"]), e["pin"], inv))
        elif e["kind"] == "adc":
            rmax = float(e.get("raw_max", 4095))
            omin = float(e.get("out_min", 0.0))
            omax = float(e.get("out_max", 1.0))
            C.append('    osodb_set_value(db, %s, %g + (%g - %g) * (double)hal_adc_read(%d) / %g, now_ms);'
                     % (cident(e["tag"]), omin, omax, omin, e["channel"], rmax))
    C.append('}')
    C.append('')
    # write outputs
    C.append('void board_io_write_outputs(osodb_t *db) {')
    for e in io:
        if e["dir"] != "out":
            continue
        if e["kind"] == "gpio":
            lvl = 'osodb_get_value(db, %s) != 0.0' % cident(e["tag"])
            if e.get("active_low"):
                lvl = '!(%s)' % lvl
            C.append('    hal_gpio_write(%d, %s);' % (e["pin"], lvl))
        elif e["kind"] == "pwm":
            omin = float(e.get("out_min", 0.0))
            omax = float(e.get("out_max", 100.0))
            C.append('    { double _v = osodb_get_value(db, %s);' % cident(e["tag"]))
            C.append('      double _d = (%g == %g) ? 0.0 : (_v - %g) / (%g - %g);' % (omax, omin, omin, omax, omin))
            C.append('      if (_d < 0) { _d = 0; }')
            C.append('      if (_d > 1) { _d = 1; }')
            C.append('      hal_pwm_write(%d, _d); }' % e["pin"])
    C.append('}')
    C.append('')
    # control loops
    C.append('void board_control_step(osodb_t *db, double dt, uint32_t now_ms) {')
    if not ctrl:
        C.append('    (void)db; (void)dt; (void)now_ms;')
    for c in ctrl:
        C.append('    { static pid_t _pid; static int _init = 0;')
        C.append('      if (!_init) { pid_init(&_pid, %g, %g, %g, %g, %g); _init = 1; }'
                 % (c.get("kp", 1.0), c.get("ki", 0.0), c.get("kd", 0.0),
                    c.get("out_min", 0.0), c.get("out_max", 100.0)))
        C.append('      double _cv = pid_step(&_pid, osodb_get_value(db, %s), osodb_get_value(db, %s), dt);'
                 % (cident(c["sp"]), cident(c["pv"])))
        C.append('      osodb_set_value(db, %s, _cv, now_ms); }' % cident(c["cv"]))
    C.append('}')

    return "\n".join(H) + "\n", "\n".join(C) + "\n"


def main(argv):
    if len(argv) < 2:
        print("usage: boardgen.py <profile.board.yaml> [-o outdir]", file=sys.stderr)
        return 2
    path = argv[1]
    outdir = "."
    if "-o" in argv:
        outdir = argv[argv.index("-o") + 1]
    os.makedirs(outdir, exist_ok=True)
    prof = parse(path)
    h, c = gen(prof)
    open(os.path.join(outdir, "board_map.h"), "w").write(h)
    open(os.path.join(outdir, "board_map.c"), "w").write(c)
    print("generated board_map.{h,c} in %s for board '%s' (%d io, %d control)"
          % (outdir, prof.get("board"), len(prof["io"]), len(prof["control"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
